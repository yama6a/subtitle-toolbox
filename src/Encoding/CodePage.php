    private const REPLACEMENT = "?";


    /**
     * Decodes bytes with a table of this class to UTF-8 and drops the bytes that the table leaves undefined.
     *
     * @param array<int, string> $table
     */
    public static function decode(string $bytes, array $table): string
    {
        $text = "";
        foreach (str_split($bytes) as $byte) {
            $text .= ord($byte) < 0x80 ? $byte : $table[ord($byte)] ?? "";
        }

        return $text;
    }


    /**
     * Encodes UTF-8 text with a table of this class and writes "?" for each character outside the table.
     *
     * @param array<int, string> $table
     */
    public static function encode(string $text, array $table): string
    {
        $bytes      = array_flip($table);
        $characters = preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY) ?: str_split($text);

        $encoded = "";
        foreach ($characters as $character) {
            $encoded .= match (true) {
                isset($bytes[$character])                          => chr($bytes[$character]),
                strlen($character) === 1 && ord($character) < 0x80 => $character,
                default                                            => self::REPLACEMENT,
            };
        }

        return $encoded;
    }
